package IsaVII.enemies.spawn;

public class EnemySpawnEntry {
    private String type;
    private double minSpawnChance;
    private double maxSpawnChance;

    public String getType() {
        return type;
    }

    public double getMinSpawnChance() {
        return minSpawnChance;
    }

    public double getMaxSpawnChance() {
        return maxSpawnChance;
    }
}
